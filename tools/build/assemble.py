#!/usr/bin/env python3
"""Assemble the uploadable device filesystem tree (framework A/B layout).

Copies the framework source (boot.py, stable A/B launcher, lib/) plus the
application (``app/`` -> ``apps/a/`` with ``main.py`` renamed to
``app_entry.py``) into ``<app-root>/device``. A local ``system-config.json``
is copied in when present.
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path


def framework_root():
    return Path(__file__).resolve().parents[2]


def resolve_app_root(cli_value=None):
    """Project root: --app-root flag > MICROPY_APP_ROOT > git superproject > CWD."""
    if cli_value:
        return Path(os.path.abspath(cli_value))
    env = os.environ.get("MICROPY_APP_ROOT")
    if env:
        return Path(os.path.abspath(env))
    root = framework_root()
    try:
        proc = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--show-superproject-working-tree"],
            capture_output=True, text=True, timeout=10)
        if proc.returncode == 0 and proc.stdout.strip():
            return Path(os.path.abspath(proc.stdout.strip()))
    except (OSError, subprocess.SubprocessError):
        pass
    return Path(os.getcwd())


def main():
    parser = argparse.ArgumentParser(
        description="Assemble the device/ A/B tree for a micropy-system project.")
    parser.add_argument("--app-root", default=None, help="application project root")
    args = parser.parse_args()

    ROOT = resolve_app_root(args.app_root)
    FRAMEWORK = framework_root() / "src"
    APP = ROOT / "app"
    DEVICE = ROOT / "device"

    if not FRAMEWORK.is_dir():
        raise SystemExit("Framework source is missing")
    if not APP.is_dir():
        raise SystemExit("Application source directory is missing: app")

    shutil.rmtree(DEVICE, ignore_errors=True)
    shutil.copytree(FRAMEWORK, DEVICE, ignore=shutil.ignore_patterns(
        "__pycache__", "*.pyc", "system-config.json", "version.txt", "slot_main.py"))
    shutil.copy2(FRAMEWORK / "slot_main.py", DEVICE / "main.py")
    slot_a = DEVICE / "apps" / "a"
    slot_a.mkdir(parents=True)
    for item in APP.iterdir():
        if item.name in ("version.txt", "__pycache__"):
            continue
        destination = slot_a / ("app_entry.py" if item.name == "main.py" else item.name)
        if item.is_dir():
            shutil.copytree(item, destination, dirs_exist_ok=True)
        else:
            shutil.copy2(item, destination)

    config = ROOT / "system-config.json"
    if config.is_file():
        shutil.copy2(config, DEVICE / "system-config.json")

    (DEVICE / ".micropy-system-device-tree").write_text(
        "Generated by tools/build/assemble.py; safe MicroPico sync root.\n",
        encoding="utf-8",
    )

    print(f"Assembled device filesystem at {DEVICE}")


if __name__ == "__main__":
    main()
